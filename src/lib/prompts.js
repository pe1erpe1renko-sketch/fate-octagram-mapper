/**
 * ПРОМПТЫ ГЕНЕРАЦИИ ТЕКСТОВ
 * =========================
 * Тексты пишутся один раз и живут в базе вечно. Значит качество промпта —
 * самое важное решение в проекте: плохой промпт в первую неделю засорит базу.
 *
 * ВЕРСИОНИРОВАНИЕ: при изменении промпта поднимите PROMPT_VERSION.
 * Тексты, созданные старой версией, помечаются устаревшими и
 * перегенерируются, а не смешиваются с новыми.
 */

export const PROMPT_VERSION = 1;

/** Названия Арканов — идут в промпт как опора, чтобы модель не путалась. */
export const ARCANA_NAMES = {
  1: 'Маг', 2: 'Жрица', 3: 'Императрица', 4: 'Император', 5: 'Иерофант',
  6: 'Влюблённые', 7: 'Колесница', 8: 'Справедливость', 9: 'Отшельник',
  10: 'Колесо Фортуны', 11: 'Сила', 12: 'Повешенный', 13: 'Смерть',
  14: 'Умеренность', 15: 'Дьявол', 16: 'Башня', 17: 'Звезда', 18: 'Луна',
  19: 'Солнце', 20: 'Суд', 21: 'Мир', 22: 'Шут',
};

export const SYSTEM_PROMPT = `Ты пишешь трактовки для сервиса «Матрица судьбы» — нумерологической системы на 22 Арканах.

КАК ПИСАТЬ
Обращайся на «вы». Пиши конкретно: не «энергия трансформации в вашей жизни», а «вы начинаете новое, только когда старое рухнуло само — заранее уходить не умеете».
Каждый абзац должен давать узнавание: человек читает и думает «это про меня».
Показывай обе стороны — сильную и теневую. Тень формулируй как механизм, а не как приговор: «вы откладываете решение, пока обстоятельства не решат за вас», а не «вы безвольны».
Заканчивай одним конкретным действием, которое можно сделать на этой неделе.

ЧЕГО НЕ ДЕЛАТЬ
Не пиши «энергия вселенной», «высшие силы ведут», «космос посылает» — это пустой звук.
Не начинай с «Аркан N означает». Начинай сразу с человека.
Не предсказывай события, болезни, смерть, беременность, суммы денег и сроки.
Не давай медицинских, психиатрических, юридических и финансовых утверждений. Про здоровье говори только как о зонах внимания и образе жизни, и не отговаривай от врача.
Не пугай. Если тема тяжёлая — говори прямо, но оставляй человеку опору и субъектность.

ФОРМАТ
2–4 абзаца, 150–250 слов. Обычный текст без markdown, заголовков и списков.`;

/**
 * @param {object} p
 * @param {string} p.sectionTitle — раздел («Через что к вам приходят деньги»)
 * @param {string} p.slotLabel — позиция («Денежный канал»)
 * @param {number} p.arcana — 1..22
 * @param {string} [p.sectionLead] — подзаголовок раздела
 */
export function buildUserPrompt({ sectionTitle, slotLabel, arcana, sectionLead }) {
  return `Раздел: «${sectionTitle}»${sectionLead ? `\nО чём раздел: ${sectionLead}` : ''}
Позиция в матрице: «${slotLabel}»
Аркан: ${arcana} — ${ARCANA_NAMES[arcana]}

Напиши трактовку именно для этой позиции. Текст должен отвечать на вопрос раздела, а не описывать Аркан вообще: один и тот же Аркан в позиции «Денежный канал» и в позиции «Линия отношений» даёт разные тексты.`;
}

/** Аркан дня — короткий формат, генерируется ежедневно. */
export function buildDailyPrompt({ arcana, periodArcana, weekday, date }) {
  return `Аркан дня: ${arcana} — ${ARCANA_NAMES[arcana]}
Аркан текущего жизненного периода человека: ${periodArcana} — ${ARCANA_NAMES[periodArcana]}
День: ${weekday}, ${date}

Напиши прогноз на день в 2–3 предложениях: на что опереться сегодня и в чём тень дня.
Учти, что аркан дня накладывается на энергию периода. Без предсказаний конкретных событий.`;
}

/** Собирает готовый запрос к модели. Провайдер подставляется на бэкенде. */
export function buildRequest(slotContext) {
  return {
    version: PROMPT_VERSION,
    system: SYSTEM_PROMPT,
    user: buildUserPrompt(slotContext),
    temperature: 0.8,
    maxTokens: 700,
  };
}
